public class sumayDoble {
    public static void main(String[] args) {
        Integer numero1 = 5;
        Integer numero2 = 10;

        Integer sumaNumeros = numero1 + numero2;
        Integer dobleNum1 = numero1 * 2;

        System.out.println("La suma de " + numero1 + " y " + numero2 + " es: " + sumaNumeros);
        System.out.println("El doble de " + numero1 + " es: " + dobleNum1);
    }
}
